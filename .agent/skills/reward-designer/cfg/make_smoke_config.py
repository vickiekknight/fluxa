#!/usr/bin/env python3
"""Generate cfg/reach_smoke.yaml from cfg/reach.yaml.

    python3 cfg/make_smoke_config.py

reach_smoke.yaml is a pure overlay on reach.yaml: identical in every respect
except the values below. Hand-editing it is how it silently fell behind once
already -- it lost the whole env_context block, so smoke runs prompted with no
environment source and nothing failed loudly. Regenerate instead.

This is a line-based transform rather than yaml.safe_load + dump so that the
comments explaining each setting survive, and it is block-aware so that
`num_samples` under `eureka:` and under `dr_eureka:` can be targeted separately
(a plain sed hits both).
"""
import re
import sys
from pathlib import Path

CFG_DIR = Path(__file__).resolve().parent
SOURCE = CFG_DIR / "reach.yaml"
TARGET = CFG_DIR / "reach_smoke.yaml"

HEADER = """# GENERATED by cfg/make_smoke_config.py from reach.yaml -- do not hand-edit.
# A reduced overlay for smoke runs: same settings as reach.yaml except for the
# sizes below and the outputs/smoke/ paths, so a smoke run cannot clobber the
# artifacts Stage 2 depends on.
#
# THIS CONFIG PROVES THE PIPELINE RUNS. ITS SCORES ARE NOT RESULTS.
# 16 envs x 20 iterations is 7,680 environment steps -- 0.008% of the 98.3M
# Isaac Lab's reference config uses for this task. At that budget the policy
# never gets near the target, success_rate sits at ~0.00-0.02 for every
# candidate, and which candidate "wins" is noise. The same reward scores 0.94
# at train_iterations=300. Use reach.yaml for anything you intend to read.

"""

# Nested overrides, keyed by the top-level block they live under.
NESTED_OVERRIDES = {
    "eureka": {
        "num_runs": "1",
        "iterations": "2",
        "num_samples": "2",
        "eval_num_envs": "16",
        "train_iterations": "20",
        "final_train_iterations": "20",
    },
    "dr_eureka": {
        "num_samples": "2",
    },
}

TOP_LEVEL_OVERRIDES = {
    "reward_output_file": '"./outputs/smoke/reward_fn.py"',
    "policy_output_file": '"./outputs/smoke/eureka_policy.pt"',
    "final_metrics_file": '"./outputs/smoke/final_metrics.json"',
}

TOP_LEVEL_KEY = re.compile(r"^([A-Za-z_][\w]*):")
NESTED_KEY = re.compile(r"^(\s+)([A-Za-z_][\w]*):")


def generate(source_text):
    out, block, applied = [], None, set()

    for line in source_text.splitlines():
        top = TOP_LEVEL_KEY.match(line)
        if top:
            block = top.group(1)
            key = top.group(1)
            if key in TOP_LEVEL_OVERRIDES:
                out.append(f"{key}: {TOP_LEVEL_OVERRIDES[key]}")
                applied.add(key)
                continue
            out.append(line)
            continue

        nested = NESTED_KEY.match(line)
        if nested and block in NESTED_OVERRIDES:
            indent, key = nested.group(1), nested.group(2)
            if key in NESTED_OVERRIDES[block]:
                value = NESTED_OVERRIDES[block][key]
                out.append(f"{indent}{key}: {value}  # smoke override")
                applied.add(f"{block}.{key}")
                continue

        out.append(line)

    expected = set(TOP_LEVEL_OVERRIDES) | {
        f"{b}.{k}" for b, keys in NESTED_OVERRIDES.items() for k in keys
    }
    missing = expected - applied
    if missing:
        raise SystemExit(
            f"ERROR: these overrides matched nothing in {SOURCE.name} "
            f"(renamed or removed?): {sorted(missing)}"
        )

    return HEADER + "\n".join(out) + "\n"


def main():
    if not SOURCE.is_file():
        raise SystemExit(f"ERROR: {SOURCE} not found")
    TARGET.write_text(generate(SOURCE.read_text()))
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
